"""Model recovery: can the fit tell the candidate models apart?

Each simulated subject is generated by one candidate model (true params drawn
from TRUE_RANGES, or the fit bounds), on structured and unstructured 8020
schedules (generate_probs_2arm, 20% impurity). Every candidate model is then
fit to both tasks; the saved table has one row per (subject, task, fitted
model) with its NLL, BIC and AIC, so the confusion matrix (generating vs
BIC-selected model) and the likelihood cost of dropping a mechanism can be
computed afterwards.

SLURM array mode: '--task-index i' runs one subject (generating model
i // n_subjects), '--merge RUN_ID' combines the partials. Submit with
slurm_scripts/submit_model_recovery_array.sh.
"""

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from numpy.random import default_rng

import mab_subjects
from banditpy.models import DecisionModel
from banditpy.models.optim import LBFGSOptimizer
from banditpy.models.policy import Qlearn, QlearnCost
from banditpy.utils.probs import generate_probs_2arm

PARTIALS_ROOT = Path(
    os.environ.get(
        "RECOVERY_PARTIALS_DIR", "/mnt/pve/Homes/bapun/Data/results/partials"
    )
)

# Candidate models: policy class plus params to enable/disable on top of the
# class defaults (Qlearn fits alpha_c, alpha_u, bias, alpha_h, sticky by default).
MODELS = {
    "base": (Qlearn, [], ["alpha_h", "sticky"]),
    "sticky": (Qlearn, [], []),
    "decay": (Qlearn, ["decay"], ["alpha_h", "sticky"]),
    "sticky_decay": (Qlearn, ["decay"], []),
    "cost": (QlearnCost, [], ["alpha_h", "sticky"]),
    "sticky_cost": (QlearnCost, [], []),
}

# True values near the 8020 animals' fits (alpha_c ~0.27, alpha_u ~-0.35,
# beta ~2.5, sticky ~1.7, |bias| < 0.3). alpha_u near +alpha_c gives agents that
# never learn, so it stops at 0.3. Params not listed (alpha_h, decay, alpha_rho)
# are drawn from their fit bounds. Override with --true-range.
TRUE_RANGES = {
    "alpha_c": (0.05, 0.9),
    "alpha_u": (-0.9, 0.3),
    "beta": (1.0, 5.0),
    "sticky": (0.0, 5.0),
    "bias": (-0.3, 0.3),
}
LOG_SCALE_PARAMS = {"beta"}


def make_policy(model):
    cls, enable, disable = MODELS[model]
    policy = cls()
    for name in enable:
        getattr(policy.params, name).enable()
    for name in disable:
        getattr(policy.params, name).disable()
    return policy


def parse_args():
    parser = argparse.ArgumentParser(description="Model recovery")
    parser.add_argument(
        "--models",
        nargs="+",
        choices=list(MODELS),
        default=["base", "sticky", "decay", "sticky_decay"],
        help="candidate models: each generates n-subjects subjects and is fit to all",
    )
    parser.add_argument(
        "--n-subjects",
        "--max-subjects",
        dest="n_subjects",
        type=int,
        default=100,
        help="subjects per generating model",
    )
    parser.add_argument("--n-blocks-per-task", type=int, default=200)
    parser.add_argument(
        "--blocks-per-session",
        type=int,
        default=1,
        help="blocks per simulated session (window); the agent resets between sessions",
    )
    parser.add_argument(
        "--true-range",
        action="append",
        default=[],
        metavar="NAME=LO,HI",
        help="override TRUE_RANGES for NAME; 'NAME=bounds' draws from the fit bounds",
    )
    parser.add_argument("--n-starts", type=int, default=12)
    parser.add_argument("--n-jobs-inner", type=int, default=6)
    parser.add_argument("--n-jobs-subject", type=int, default=4, help="local mode only")
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--tag", default="", help="suffix for the save name")
    parser.add_argument("--task-index", type=int, default=None)
    parser.add_argument("--merge", metavar="RUN_ID", default=None)
    return parser.parse_args()


def main():
    args = parse_args()

    true_ranges = dict(TRUE_RANGES)
    for spec in args.true_range:
        name, _, rng_txt = spec.partition("=")
        if rng_txt == "bounds":
            true_ranges.pop(name, None)
        else:
            lo, hi = (float(x) for x in rng_txt.split(","))
            true_ranges[name] = (lo, hi)

    n_tasks = len(args.models) * args.n_subjects
    child_seed_seqs = np.random.SeedSequence(args.seed).spawn(n_tasks)
    fit_kwargs = dict(
        optimizer=LBFGSOptimizer(),
        early_stop=False,
        n_starts=args.n_starts,
        n_jobs=args.n_jobs_inner,
    )

    def sample_true_policy(model, rng):
        policy = make_policy(model)
        bounds = policy.get_bounds()
        values = {}
        for name in policy.active_parameter_names():
            lo, hi = bounds[name]
            lo, hi = true_ranges.get(name, (lo, hi))
            if name in LOG_SCALE_PARAMS:
                values[name] = float(np.exp(rng.uniform(np.log(lo), np.log(hi))))
            else:
                values[name] = float(rng.uniform(lo, hi))
        policy.set_params(values)
        return policy, values

    def run_one(i):
        gen_model = args.models[i // args.n_subjects]
        rng = default_rng(child_seed_seqs[i])
        policy, truth = sample_true_policy(gen_model, rng)
        probs_unstruc, probs_struc = generate_probs_2arm(
            N=args.n_blocks_per_task, frac_impurity=0.2
        )
        rows = []
        for task_name, probs in (("unstruc", probs_unstruc), ("struc", probs_struc)):
            task = DecisionModel.simulate_policy(
                policy=policy,
                reward_schedule=probs,
                min_trials_per_block=100,
                prob_switch=0.02,
                seed=rng.integers(2**32),
                blocks_per_session=args.blocks_per_session,
            )
            n_trials = len(task.choices)
            switch = float(np.mean(task.choices[1:] != task.choices[:-1]))
            for fit_model in args.models:
                model = DecisionModel(
                    task=task, policy=make_policy(fit_model), reset_mode="session"
                )
                model.fit(**fit_kwargs)
                names = model.policy.active_parameter_names()
                k, nll = len(names), float(model.nll)
                row = dict(
                    sim_id=i,
                    gen_model=gen_model,
                    task=task_name,
                    fit_model=fit_model,
                    n_params=k,
                    n_trials=n_trials,
                    switch_rate=switch,
                    nll=nll,
                    bic=2 * nll + k * np.log(n_trials),
                    aic=2 * nll + 2 * k,
                    true_params=truth,
                    fit_params={p: float(model.params[p]) for p in names},
                )
                if fit_model == gen_model:
                    row["nll_true"] = float(
                        model._nll(np.array([truth[p] for p in names]))
                    )
                rows.append(row)
        df = pd.DataFrame(rows)
        df["true_ranges"] = ", ".join(f"{n}: [{lo:g}, {hi:g}]" for n, (lo, hi) in true_ranges.items())
        return df

    save_name = "model_recovery_" + "_".join(args.models)
    if args.tag:
        save_name = f"{save_name}_{args.tag}"
    partials_dir = PARTIALS_ROOT / save_name

    if args.merge is not None:
        run_dir = partials_dir / args.merge
        files = sorted(run_dir.glob("*.pkl"))
        missing = sorted(set(range(n_tasks)) - {int(f.stem) for f in files})
        if missing:
            raise SystemExit(
                f"Not merging {run_dir}: {len(missing)} missing tasks, e.g. {missing[:10]}"
            )
        df = pd.concat([pd.read_pickle(f) for f in files], ignore_index=True)
        print(f"Merging {len(files)} partials from {run_dir} -> {save_name}")
        mab_subjects.GroupData().save(df, save_name, write_stub=False)
        return

    if args.task_index is not None:
        run_dir = partials_dir / os.environ.get("SLURM_ARRAY_JOB_ID", "local")
        run_dir.mkdir(parents=True, exist_ok=True)
        out = run_dir / f"{args.task_index:04d}.pkl"
        run_one(args.task_index).to_pickle(out)
        print(f"Wrote {out}")
        return

    results = Parallel(n_jobs=args.n_jobs_subject)(
        delayed(run_one)(i) for i in range(n_tasks)
    )
    df = pd.concat(results, ignore_index=True)
    mab_subjects.GroupData().save(df, save_name, write_stub=False)


if __name__ == "__main__":
    main()
